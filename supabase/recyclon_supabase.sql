-- Recyclon Supabase PostgreSQL schema
-- Paste into Supabase Dashboard -> SQL Editor -> New query -> Run.
-- This preserves the existing PHP application's table and column names.
-- It intentionally contains no production users, passwords, or private data.

create extension if not exists pgcrypto;

create table if not exists public.users (
    user_id bigint generated by default as identity primary key,
    auth_user_id uuid unique,
    name varchar(100) not null,
    email varchar(255) unique,
    password varchar(255),
    phone varchar(32),
    ic_number varchar(64),
    bank_name varchar(100),
    bank_account_number varchar(100),
    role text check (role in ('Admin', 'Staff', 'Driver', 'Customer')),
    address varchar(255),
    status text not null default 'Active' check (status in ('Active', 'Inactive')),
    created_at timestamptz not null default now(),
    google_id varchar(255),
    auto_accept_bookings boolean not null default false
);

-- Keep existing Supabase projects compatible when this schema is re-applied.
alter table public.users
    add column if not exists auto_accept_bookings boolean not null default false;

create table if not exists public.lorries (
    lorry_id bigint generated by default as identity primary key,
    plate_number varchar(20) not null unique,
    driver_id bigint references public.users(user_id) on delete set null,
    status text not null default 'Available' check (status in ('Available', 'On Duty', 'Maintenance')),
    current_lat numeric(10,7),
    current_long numeric(10,7),
    last_updated timestamptz,
    destination_lat double precision,
    destination_long double precision,
    destination_set_at timestamptz
);

create table if not exists public.waste_categories (
    waste_id bigint generated by default as identity primary key,
    category_name varchar(50) not null,
    unit_price numeric(10,2),
    unit varchar(10) not null default 'kg',
    image_icon varchar(255),
    status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

create table if not exists public.booking (
    booking_id bigint generated by default as identity primary key,
    customer_id bigint references public.users(user_id) on delete set null,
    driver_id bigint references public.users(user_id) on delete set null,
    customer_name varchar(100),
    staff_id bigint references public.users(user_id) on delete set null,
    lorry_id bigint references public.lorries(lorry_id) on delete set null,
    address varchar(255) not null default '',
    note text,
    pickup_date date,
    booking_date date not null default current_date,
    scheduled_date timestamptz,
    status text not null default 'Pending' check (status in ('Pending', 'Scheduled', 'Completed', 'Cancelled', 'Confirmed')),
    booking_type text not null default 'pickup' check (booking_type in ('pickup', 'walkin')),
    created_at timestamptz not null default now()
);

create table if not exists public.sales (
    sale_id bigint generated by default as identity primary key,
    customer_id bigint references public.users(user_id) on delete set null,
    staff_id bigint references public.users(user_id) on delete set null,
    booking_id bigint references public.booking(booking_id) on delete set null,
    lorry_id bigint references public.lorries(lorry_id) on delete set null,
    total_amount numeric(10,2) not null default 0,
    sale_date timestamptz not null default now(),
    payment_status text not null default 'Pending' check (payment_status in ('Paid', 'Pending', 'Cancelled'))
);

create table if not exists public.sale_items (
    item_id bigint generated by default as identity primary key,
    sale_id bigint references public.sales(sale_id) on delete cascade,
    waste_id bigint references public.waste_categories(waste_id) on delete set null,
    weight_kg numeric(10,2),
    price_per_kg numeric(10,2),
    subtotal numeric(10,2)
);

create table if not exists public.price_history (
    history_id bigint generated by default as identity primary key,
    waste_id bigint references public.waste_categories(waste_id) on delete set null,
    old_price numeric(10,2),
    new_price numeric(10,2),
    changed_by bigint references public.users(user_id) on delete set null,
    changed_at timestamptz not null default now()
);

create table if not exists public.gps_log (
    log_id bigint generated by default as identity primary key,
    lorry_id bigint not null references public.lorries(lorry_id) on delete cascade,
    latitude numeric(10,7) not null,
    longitude numeric(10,7) not null,
    recorded_at timestamptz not null default now()
);

create table if not exists public.arrival_queue (
    id bigint generated by default as identity primary key,
    booking_id bigint references public.booking(booking_id) on delete set null,
    driver_id bigint references public.users(user_id) on delete set null,
    assigned_lorry_id bigint references public.lorries(lorry_id) on delete set null,
    created_by bigint references public.users(user_id) on delete set null,
    driver_name varchar(255),
    plate_number varchar(64),
    geolocation varchar(255),
    location_name varchar(255),
    latitude numeric(10,7),
    longitude numeric(10,7),
    priority integer not null default 100,
    notes text,
    status text not null default 'pending' check (status in ('pending', 'ongoing', 'completed', 'cancelled')),
    assigned_at timestamptz,
    completed_at timestamptz,
    updated_at timestamptz not null default now(),
    created_at timestamptz not null default now()
);

