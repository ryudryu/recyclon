drop policy if exists users_self_select on public.users;
create policy users_self_select on public.users for select to authenticated
using (auth_user_id = auth.uid() or public.current_app_role() in ('Admin', 'Staff'));

drop policy if exists users_admin_manage on public.users;
create policy users_admin_manage on public.users for all to authenticated
using (public.current_app_role() = 'Admin') with check (public.current_app_role() = 'Admin');

drop policy if exists waste_authenticated_read on public.waste_categories;
