drop policy if exists waste_staff_manage on public.waste_categories;
create policy waste_staff_manage on public.waste_categories for all to authenticated
using (public.current_app_role() in ('Admin', 'Staff')) with check (public.current_app_role() in ('Admin', 'Staff'));

create or replace function public.can_access_booking(row_customer_id bigint, row_driver_id bigint, row_staff_id bigint)
returns boolean language sql stable security definer set search_path = public
as $$
    select public.current_app_role() in ('Admin', 'Staff')
        or exists (select 1 from public.users u where u.auth_user_id = auth.uid() and (u.user_id = row_customer_id or u.user_id = row_driver_id or u.user_id = row_staff_id));
$$;

