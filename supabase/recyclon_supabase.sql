-- Starter pricing rows keep the new-booking form usable on a fresh project.
-- Existing categories are preserved; each row is inserted only when its name
-- is not already present.
insert into public.waste_categories (category_name, unit_price, unit, status)
select seed.category_name, seed.unit_price, seed.unit, 'Active'
from (values
    ('Paper Box', 1.00::numeric, 'kg'),
    ('Paper', 0.80::numeric, 'kg'),
    ('Metal', 2.50::numeric, 'kg'),
    ('Plastic', 1.50::numeric, 'kg'),
    ('Rubbish', 0.50::numeric, 'kg'),
    ('Tin', 0.80::numeric, 'kg')
) as seed(category_name, unit_price, unit)
where not exists (
    select 1 from public.waste_categories existing
    where lower(existing.category_name) = lower(seed.category_name)
);

-- Keep timestamps current for queue updates.
create or replace function public.set_arrival_queue_updated_at()
returns trigger language plpgsql as $$
begin
    new.updated_at = now();
    if new.status = 'ongoing' and old.status is distinct from 'ongoing' and new.assigned_at is null then
        new.assigned_at = now();
    end if;
    if new.status = 'completed' and old.status is distinct from 'completed' and new.completed_at is null then
        new.completed_at = now();
    end if;
    return new;
end;
$$;

drop trigger if exists arrival_queue_updated_at on public.arrival_queue;
create trigger arrival_queue_updated_at
before update on public.arrival_queue
for each row execute function public.set_arrival_queue_updated_at();

-- Supabase Auth role helpers. Link a row in users.auth_user_id to auth.users.id
-- when moving an account to Supabase Auth.
create or replace function public.current_app_role()
returns text language sql stable security definer set search_path = public
as $$ select role from public.users where auth_user_id = auth.uid() limit 1 $$;

